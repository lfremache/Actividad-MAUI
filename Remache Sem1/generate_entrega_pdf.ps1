# Script para generar un PDF simple de entrega dentro del repositorio
Param(
	[string]$OutputPath = "Entrega_Actividad1.pdf"
)

# Objetos PDF como cadenas (sin calcular offsets aún)
$obj1 = "1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n"
$obj2 = "2 0 obj\n<< /Type /Pages /Count 1 /Kids [3 0 R] >>\nendobj\n"
$obj3 = "3 0 obj\n<< /Type /Page /Parent 2 0 R /Resources << /Font << /F1 4 0 R >> >> /MediaBox [0 0 612 792] /Contents 5 0 R >>\nendobj\n"
$obj4 = "4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n"

# Contenido de la página (texto). Usamos operadores PDF para posicionar texto.
$lines = @(
	"BT",
	"/F1 14 Tf",
	"50 760 Td",
	"(Entrega de la Actividad 1 - C\´alculo Aporte IESS) Tj",
	"50 740 Td",
	"(Alumno: Lenin Remache) Tj",
	"50 720 Td",
	"(Descripcion: Aplicacion .NET MAUI que calcula 9.45% del salario y muestra alerta) Tj",
	"50 700 Td",
	"(Entradas: Nombre, Apellido, Edad, Salario) Tj",
	"50 680 Td",
	"(Validaciones: Campos obligatorios; Edad y Salario numericos) Tj",
	"50 660 Td",
	"(Salida: Alerta con formato y saltos de linea) Tj",
	"50 640 Td",
	"(Repositorio: https://github.com/lfremache/Actividad-MAUI) Tj",
	"ET"
)

$streamContent = ($lines -join "\n") + "\n"

$obj5Stream = $streamContent
$length = [System.Text.Encoding]::ASCII.GetByteCount($obj5Stream)
$obj5 = "5 0 obj\n<< /Length $length >>\nstream\n" + $obj5Stream + "endstream\nendobj\n"

# Header
$header = "%PDF-1.4\n%Generated by script\n"

# Construir el contenido completo y calcular offsets para xref
$parts = @($header, $obj1, $obj2, $obj3, $obj4, $obj5)

$offsets = @()
$pos = 0
foreach ($p in $parts) {
	$offsets += $pos
	$pos += [System.Text.Encoding]::ASCII.GetByteCount($p)
}

# Construir xref
$xref = "xref\n0 6\n"
$xref += "0000000000 65535 f \n"
foreach ($o in $offsets) {
	$xref += '{0:d10} 00000 n \n' -f $o
}

$trailer = "trailer\n<< /Size 6 /Root 1 0 R >>\n"
$startxref = $pos

$full = ($parts -join "") + $xref + $trailer + "startxref\n" + $startxref + "\n%%EOF\n"

# Escribir archivo en la ruta especificada
[System.IO.File]::WriteAllText(($OutputPath), $full, [System.Text.Encoding]::ASCII)

Write-Host "PDF generado en: $OutputPath"
